def e(x): return html.escape(str(x), quote=True)


def shelf_url(sec):
    """The shelf on its category page (build.py CATEGORIES), where it is shown in
    full; the home page now shows only the first few books of a long shelf."""
    cat = ("classics" if sec["id"] == "classics" else "young-readers" if sec.get("kids")
           else "money" if sec.get("nonfic") else "fiction")
    return f"/{cat}/#h-{sec['id']}"


def slugify(s):
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()
    s = re.sub(r"[^a-z0-9]+", "-", s.lower().replace(",", ""))
    return s.strip("-")


def display_title(b, sec):
    """The omnibus is titled "The Complete Series" in the catalogue, which means
    nothing in a search result on its own, so it carries its series name."""
    return f'{sec["name"]}: {b["t"]}' if b.get("omnibus") else b["t"]


def records(D):
    """[(book, section, slug)] in catalogue order. Slugs must be unique."""
    out, seen = [], {}
    for sec in D["sections"]:
        for b in sec["books"]:
            slug = slugify(display_title(b, sec))
            if slug in seen:
                raise SystemExit(f'books.py: slug {slug!r} is shared by {seen[slug]} and {b["a"]}')
            seen[slug] = b["a"]
            out.append((b, sec, slug))
    return out


def url_for(D):
    """{asin: "/books/<slug>/"}, for the homepage tiles."""
    return {b["a"]: f"/books/{slug}/" for b, _, slug in records(D)}


def _own_line(D, asin):
    """The catalogue's own words for this one title, or None."""
    B = D.get("bestseller") or {}
    if B.get("enabled") and B.get("lead") == asin and B.get("blurb"):
        return B["blurb"]
    for band in ((D.get("featured") or {}).get("books", []), B.get("connected") or []):
        for f in band:
            if f.get("a") == asin and f.get("why"):
                return f["why"]
    return None


