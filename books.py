def print_pages(asin):
    """The print edition's page count from formats.json (paperback first), or None."""
    fmts = (FORMATS["books"].get(asin) or {}).get("formats", [])
    for want in ("Paperback", "Hardcover"):
        for f in fmts:
            if f.get("f") == want and f.get("pages"):
                return int(f["pages"])
    return None


