"""One page per title, at /books/<slug>/, generated from catalog.json.

WHY. Every book used to live only as a card on the homepage, so Google had one
url to rank for 86 titles. A page per book gives each title its own search
entry: its own <title>, description, canonical url and Book structured data.

THE COPY IS THE CATALOGUE'S, NEVER NEW. A page shows the title's own `hook` if it
has one, else the editorial line the catalogue already wrote for it in the
bestseller or Start Here bands, verbatim. Nothing is paraphrased, summarised or
invented here. The shelf blurb rides along as context and is labelled as being
about the shelf, not the book. A title with no line of its own simply has none.

HOUSE RULES ENFORCED AT BUILD TIME, because a rule nobody checks drifts:
  - no em or en dash anywhere in a page,
  - no "best seller" wording (that claim lives only in the sourced band),
  - the buy link says "available on Amazon" and names no format and no price.
A page that breaks one stops the build.

`isbn` is emitted only when a catalogue record carries one. The catalogue keys
on ASIN, and an ASIN is not an ISBN and must never be passed off as one.
"""
import html, json, os, re, shutil, unicodedata

import nav

AMZ = "https://www.amazon.com/dp/{}"
REVIEW = "https://www.amazon.com/review/create-review?asin={}"
MARK = "<!-- GENERATED by books.py -->"
FORMAT_ONLY = {"paperback", "hardcover", "ebook", "kindle", "kindle edition"}


def e(x): return html.escape(str(x), quote=True)


def slugify(s):
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode()
    s = re.sub(r"[^a-z0-9]+", "-", s.lower().replace(",", ""))
    return s.strip("-")


def display_title(b, sec):
    """The omnibus is titled "The Complete Series" in the catalogue, which means
    nothing in a search result on its own, so it carries its series name."""
    return f'{sec["name"]}: {b["t"]}' if b.get("omnibus") else b["t"]


def records(D):
    """[(book, section, slug)] in catalogue order. Slugs must be unique."""
    out, seen = [], {}
    for sec in D["sections"]:
        for b in sec["books"]:
            slug = slugify(display_title(b, sec))
            if slug in seen:
                raise SystemExit(f'books.py: slug {slug!r} is shared by {seen[slug]} and {b["a"]}')
            seen[slug] = b["a"]
            out.append((b, sec, slug))
    return out


def url_for(D):
    """{asin: "/books/<slug>/"}, for the homepage tiles."""
    return {b["a"]: f"/books/{slug}/" for b, _, slug in records(D)}


def _own_line(D, asin):
    """The catalogue's own words for this one title, or None."""
    B = D.get("bestseller") or {}
    if B.get("enabled") and B.get("lead") == asin and B.get("blurb"):
        return B["blurb"]
    for band in ((D.get("featured") or {}).get("books", []), B.get("connected") or []):
        for f in band:
            if f.get("a") == asin and f.get("why"):
                return f["why"]
    return None


