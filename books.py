BANNED = [("—", "em dash"), ("–", "en dash"), ("&mdash;", "em dash"),
          ("&ndash;", "en dash"), ("best sell", "best seller claim"),
          ("bestsell", "best seller claim"), ("best-sell", "best seller claim")]


def _guard(path, s):
    low = s.lower()
    for needle, what in BANNED:
        if needle in low:
            raise SystemExit(f"books.py: {path} contains an {what} ({needle!r}). House rule.")


def build(D, S, root="books"):
    """Write every book page; remove pages for titles no longer in the catalogue.
    Returns the list of url paths written, for the sitemap."""
    recs = records(D)
    os.makedirs(root, exist_ok=True)
    keep = {slug for _, _, slug in recs}
    for d in os.listdir(root):
        p = os.path.join(root, d, "index.html")
        # Only a directory this module made is removed, never anything hand-placed.
        if d not in keep and os.path.isfile(p) and MARK in open(p, encoding="utf-8").read():
            shutil.rmtree(os.path.join(root, d))
    by_sec = {}
    for r in recs:
        by_sec.setdefault(r[1]["id"], []).append(r)
    paths = []
    for b, sec, slug in recs:
        shelf = by_sec[sec["id"]]
        i = next(k for k, r in enumerate(shelf) if r[0]["a"] == b["a"])
        # The titles that follow this one on its shelf, wrapping, at most twelve:
        # every page links onward, and no page links to all thirty classics.
        siblings = [shelf[(i + k) % len(shelf)] for k in range(1, min(len(shelf), 13))]
        s = _page(D, S, b, sec, slug, siblings)
        path = os.path.join(root, slug, "index.html")
        _guard(path, s)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(s)
        nav.patch(path)
        paths.append(f"/{root}/{slug}/")
    return paths
